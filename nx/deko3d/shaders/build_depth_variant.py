"""Build the position-only variant from the GLSL that produced the installed shader."""
import argparse
import re
import subprocess
import tempfile
from pathlib import Path

parser = argparse.ArgumentParser()
for argument in ("uam", "glsl", "installed_dksh", "output_header"):
    parser.add_argument(argument, type=Path)
args = parser.parse_args()
original = args.installed_dksh.read_bytes()
with tempfile.TemporaryDirectory() as tmp:
    binary = Path(tmp) / "shader.dksh"

    def compile_vertex(path):
        subprocess.run([args.uam, "-s", "vert", "-o", binary, path], check=True)
        return binary.read_bytes()

    if compile_vertex(args.glsl) != original:
        raise ValueError("The compiler and source must reproduce the installed shader")
    source = args.glsl.read_text()
    interface = r"out_var_(?:TEXCOORD|COLOR)\d+"
    source, decls = re.subn(rf"(?m)^layout\(location = \d+\) out vec4 {interface};\n", "", source)
    source, writes = re.subn(rf"(?m)^ +{interface} = vec4\(0\.0\);\n", "", source)
    if (decls, writes) != (22, 22) or "out_var_" in source:
        raise ValueError("Unexpected shader interface")
    vertex = Path(tmp) / "depth.vert"
    vertex.write_text(source)
    optimized = compile_vertex(vertex)

lines = ["// Generated by nx/deko3d/shaders/build_depth_variant.py", "#pragma once", "#include <cstdint>"]
for name, data in (("kDepthVariantBase", original), ("kDepthVariantCode", optimized)):
    lines.append(f"alignas(256) inline constexpr uint8_t {name}[] = {{")
    for start in range(0, len(data), 16):
        lines.append("  " + ", ".join(map(str, data[start:start + 16])) + ",")
    lines.append("};")
args.output_header.write_text("\n".join(lines) + "\n")
