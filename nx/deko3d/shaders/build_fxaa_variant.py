"""Specialize the two FXAA shader variants for zero texture sign masks."""
import argparse
import subprocess
import tempfile
from pathlib import Path

parser = argparse.ArgumentParser()
for arg in ("uam", "glsl_dir", "package", "output_header"):
    parser.add_argument(arg, type=Path)
args = parser.parse_args()
lines = ["// Generated by build_fxaa_variant.py", "#pragma once", "#include <cstdint>"]
with tempfile.TemporaryDirectory() as tmp:
    work = Path(tmp)
    for suffix, symbol in (("", "Alpha"), ("_nat", "NoAlpha")):
        stem = "ps_689a4cc6402ab00b" + suffix
        source = args.glsl_dir / (stem + ".glsl")
        binary = work / "shader.dksh"
        command = [args.uam, "-s", "frag", "-o", binary]
        subprocess.run(command + [source], check=True)
        original = binary.read_bytes()
        if original != (args.package / (stem + ".dksh")).read_bytes():
            raise ValueError(f"Source does not reproduce installed {stem}")
        text = source.read_text()
        for component in "xy":
            expr = f"floatBitsToUint(g_UboShared.v[0].{component}) >> 24u"
            if text.count(expr) != 1:
                raise ValueError(f"Unexpected sign mask in {stem}")
            text = text.replace(expr, "0u")
        specialized = work / "specialized.glsl"
        specialized.write_text(text)
        subprocess.run(command + [specialized], check=True)
        for kind, data in (("Base", original), ("Code", binary.read_bytes())):
            lines.append(f"alignas(256) inline constexpr uint8_t kFxaa{symbol}{kind}[] = {{")
            for at in range(0, len(data), 24):
                lines.append("  " + ", ".join(map(str, data[at:at + 24])) + ",")
            lines.append("};")
args.output_header.write_text("\n".join(lines) + "\n")
